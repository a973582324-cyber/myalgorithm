#include<iostream>
using namespace std;
//函数重载
//函数重载是指在同一个作用域内，允许存在多个函数名相同但参数列表不同的函数。编译器根据函数调用时提供的实参类型和数量来选择匹配的函数版本进行调用。
//函数重载可以提高代码的可读性和可维护性，使得函数能够适用于不同类型和数量的参数。函数重载的规则是：
//1. 函数名相同，参数列表不同（参数类型、参数数量或参数顺序不同）
//2. 函数返回类型不同不能构成函数重载
//3. 函数重载不能仅通过参数的默认值来区分
//4. 函数重载不能通过参数的类型转换来区分
//函数重载的注意事项：
//1. 函数重载可能会导致歧义，如果编译器无法确定调用哪个函数版本，会产生编译错误。因此，在设计函数重载时要确保每个函数版本的参数列表足够明确，避免歧义。
//2. 函数重载可能会增加编译时间和代码维护的复杂度，因为编译器需要检查每个函数调用的参数类型和数量来确定匹配的函数版本。因此，在使用函数重载时要权衡其带来的便利性和潜在的复杂性。
//引用作为函数参数时，函数重载的规则同样适用。引用类型的参数可以参与函数重载，但需要注意以下几点：
//1. 引用类型的参数可以是左值引用（T&）或右值引用（T&&）。这两种引用类型在函数重载中被视为不同的参数类型，可以用于区分函数版本。
//2. 引用类型的参数可以与非引用类型的参数进行重载。例如，函数可以同时定义一个接受整数参数的版本和一个接受整数引用参数的版本，这样在调用时根据实参的类型来选择合适的函数版本。
//左值：指的是具有持久地址的对象，可以在程序中被多次访问和修改。例如，变量、数组元素、函数返回的引用等都是左值。左值可以出现在赋值语句的左侧，也可以作为函数参数传递。
//右值：指的是没有持久地址的临时对象，通常是表达式的求值结果。右值不能出现在赋值语句的左侧，但可以作为函数参数传递。
//例如，考虑以下函数重载示例，其中一个函数接受常量整数引用参数，另一个函数接受整数引用参数：
//函数重载遇到默认参数时，编译器会根据实参的类型和数量来选择匹配的函数版本。如果实参的类型和数量与某个函数版本完全匹配，则调用该版本；如果实参的类型和数量与多个函数版本匹配，则会产生歧义错误；如果实参的类型和数量与任何函数版本都不匹配，则会产生编译错误。
void func(int &a)// 这个函数接受一个整数引用参数
{
    cout << "func(int a) called with a = " << a << endl;
}
void func(const int &a)// 这个函数接受一个常量整数引用参数
{
    cout << "func(const int &a) called with a = " << a << endl;
}
//函数重载的示例
void func(int a) {
    cout << "func(int a) called with a = " << a << endl;
}
void func(double a) {
    cout << "func(double a) called with a = " << a << endl;
}
void func(int a, int b) {
    cout << "func(int a, int b) called with a = " << a << ", b = " << b << endl;
}
int main() {
    func(10);// 调用 func(int a)和 func(const int &a)之间存在歧义，因为实参10既可以匹配整数参数，也可以匹配常量整数引用参数，因此会产生编译错误。 
    func(3.14); // 调用 func(double a)
    func(5, 15); // 调用 func(int a, int b)
    return 0;
}