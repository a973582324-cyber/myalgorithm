#include<iostream>
using namespace std;
//栈区注意--不要返回局部变量地址
//栈区的内存由编译器自动分配和释放，局部变量在函数调用结束后会被销毁，因此返回局部变量的地址是危险的，因为它可能会被其他数据覆盖，导致不可预测的行为。
//如果需要返回一个指针，可以使用动态内存分配（如new）来
//分配内存，或者使用静态变量来存储数据，这样它们的生命周期就不会受到函数调用的限制。
//堆区注意--使用完毕后要释放内存
//堆区的内存由程序员手动分配和释放，使用new运算符分配内存后，必须使用delete运算符释放内存，否则会导致内存泄漏。 
//在C++11及以后的版本中，可以使用智能指针（如std::unique_ptr和std::shared_ptr）来自动管理堆内存，避免内存泄漏的问题。 
int* func()
{
    int a = 10; //局部变量，存储在栈区
    return &a; //返回局部变量的地址，危险！
}
int* func2()
{
    int* p = new int(10); //动态分配内存，存储在堆区
    return p; //返回堆区内存的地址，安全！
}
int main()
{
    int* p = func(); //调用函数，获取局部变量的地址
    cout << *p << endl; //可能会输出10，但也可能输出垃圾值，因为a已经被销毁了
    int* p2 = func2(); //调用函数，获取堆区内存的地址
    cout << *p2 << endl; //输出10，因为堆区内存仍然存在
    delete p; //释放内存
    delete p2; //释放内存
    return 0;
}